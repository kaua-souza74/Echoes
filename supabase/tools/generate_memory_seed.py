"""Generate the reviewed SQL catalog from the existing authored JSON, without IDs changing."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
catalog = json.loads((ROOT / 'flutter_app/assets/narrative/memory_catalog.json').read_text(encoding='utf-8'))
ids = {
    prop['id'] for stage in ('stage_01', 'stage_02', 'stage_03')
    for prop in json.loads((ROOT / f'flutter_app/assets/levels/{stage}.json').read_text(encoding='utf-8'))['props']
    if prop['type'] == 'echo'
}
assert ids == {entry['collectible_id'] for entry in catalog['entries']}
assert len(ids) == len(catalog['entries']) == 21

def quote(value):
    return "'" + value.replace("'", "''") + "'"

columns = ('id', 'collectible_id', 'stage_id', 'title', 'narrative', 'character_or_event', 'concept', 'explanation', 'illustration_asset')
rows = ["(" + ','.join(quote(entry[key]) for key in columns) + ")" for entry in catalog['entries']]
sql = '-- Generated by tools/generate_memory_seed.py from memory_catalog.json.\nbegin;\n'
sql += 'insert into public.memory_entries (' + ','.join(columns) + ') values\n' + ',\n'.join(rows)
sql += '\non conflict(id) do update set ' + ','.join(f'{key}=excluded.{key}' for key in columns[1:]) + ';\n'
for check in catalog['learning_checks']:
    assignments = {
        'prompt': quote(check['prompt']), 'options': quote(json.dumps(check['options'], ensure_ascii=False)) + '::jsonb',
        'feedback_correct': quote(check['feedback_correct']), 'feedback_incorrect': quote(check['feedback_incorrect']),
        'correct_index': str(check['correct_index']),
    }
    sql += 'update public.learning_checks set ' + ','.join(f'{key}={value}' for key, value in assignments.items()) + ' where id=' + quote(check['id']) + ';\n'
sql += 'commit;\n'
target = ROOT / 'supabase/seeds/memory_catalog.sql'
target.parent.mkdir(parents=True, exist_ok=True)
target.write_text(sql, encoding='utf-8')
print(f'Generated {len(rows)} memories and {len(catalog["learning_checks"])} checks; all 21 level IDs match.')
